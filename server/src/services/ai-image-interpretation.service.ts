import { Injectable } from '@nestjs/common';
import { Cron } from '@nestjs/schedule';
import sharp from 'sharp';
import type { ArgOf } from 'src/repositories/event.repository.js';
import type { IAssetInterpretationJob, JobOf } from 'src/types.js';
import { OnEvent, OnJob } from 'src/decorators.js';
import { AiInterpretationInput, AiInterpretationMetrics } from 'src/dtos/ai-image-interpretation.dto.js';
import { AssetFileType, AssetType, AssetVisibility, ImmichWorker, JobName, JobStatus, QueueName } from 'src/enum.js';
import {
  AiImageInterpretationRepository,
  type AiInterpretationClaimOptions,
  type AiInterpretationIdentity,
} from 'src/repositories/ai-image-interpretation.repository.js';
import { AssetJobRepository } from 'src/repositories/asset-job.repository.js';
import { AssetRepository } from 'src/repositories/asset.repository.js';
import { ConfigRepository } from 'src/repositories/config.repository.js';
import { JobRepository } from 'src/repositories/job.repository.js';
import { LoggingRepository } from 'src/repositories/logging.repository.js';
import { SystemMetadataRepository } from 'src/repositories/system-metadata.repository.js';
import {
  AiImageInterpretationClient,
  AiImageInterpretationClientError,
} from 'src/services/ai-image-interpretation.client.js';
import {
  AI_INTERPRETATION_HOSTED_QUANT,
  createAiInterpretationJobId,
  createAiInterpretationPublicRunKey,
} from 'src/utils/ai-image-interpretation.js';
import { getAssetFile } from 'src/utils/asset.util.js';
import { getConfig } from 'src/utils/config.js';
import { isDuplicateDetectionEnabled } from 'src/utils/misc.js';

type PreparedPreview = {
  buffer: Buffer;
  input: AiInterpretationInput;
};

// Previews are generated by Immich itself, so exceeding the pixel budget is a
// normal extreme-aspect screenshot (scroll captures reach 30+ MP), not a
// hostile file — those get clamped by the maxEdge resize instead of failing.
// Only decode bombs above sharp's own default ceiling still fail hard.
const MAX_DECODE_PIXELS = 268_402_689;

// A main-queue retry only re-enters the upload band (2) while its asset is
// young enough to plausibly be a fresh upload's failing delivery; older assets
// drop to the bulk-script band (3) so failure cycles cannot re-flood tier 2.
const UPLOAD_RETRY_MAX_ASSET_AGE_MS = 24 * 60 * 60 * 1000;

@Injectable()
export class AiImageInterpretationService {
  constructor(
    private logger: LoggingRepository,
    private configRepository: ConfigRepository,
    private assetJobRepository: AssetJobRepository,
    private assetRepository: AssetRepository,
    private systemMetadataRepository: SystemMetadataRepository,
    private jobRepository: JobRepository,
    private interpretationRepository: AiImageInterpretationRepository,
    private client: AiImageInterpretationClient,
  ) {
    this.logger.setContext(AiImageInterpretationService.name);
  }

  @OnEvent({ name: 'AppBootstrap', workers: [ImmichWorker.Microservices] })
  async onBootstrap() {
    if (this.configRepository.getEnv().aiImageInterpretation.enabled) {
      await this.jobRepository.queue({ name: JobName.AssetInterpretationReconcile });
    }
  }

  @Cron('*/15 * * * *')
  async reconcilePeriodically() {
    if (
      this.configRepository.getWorker() !== ImmichWorker.Microservices ||
      !this.configRepository.getEnv().aiImageInterpretation.enabled
    ) {
      return;
    }

    await this.reconcile();
  }

  // Upload-path trigger: the duplicate service emits once duplicate analysis has
  // concluded for the asset (final pass, exclusion, or feature off), so
  // interpretation can deduplicate against already-interpreted group members
  // instead of racing the duplicate pipeline.
  @OnEvent({ name: 'AssetDuplicateDetectionCompleted', workers: [ImmichWorker.Microservices] })
  async onDuplicateDetectionCompleted({ assetId }: ArgOf<'AssetDuplicateDetectionCompleted'>) {
    const runKey = await this.claimMissingRun(assetId);
    if (!runKey) {
      return;
    }

    await this.jobRepository.queue({
      name: JobName.AssetInterpretImage,
      data: { id: assetId, runKey, source: 'upload', priority: 2 },
    });
  }

  @OnJob({ name: JobName.AssetInterpretImage, queue: QueueName.ImageInterpretation })
  async handleInterpretation(job: JobOf<JobName.AssetInterpretImage>): Promise<JobStatus> {
    return this.deliver(job, false);
  }

  @OnJob({ name: JobName.AssetInterpretImagePublic, queue: QueueName.ImageInterpretationPublic })
  async handleInterpretationPublic(job: JobOf<JobName.AssetInterpretImagePublic>): Promise<JobStatus> {
    return this.deliver(job, true);
  }

  // `forcePublic` marks deliveries riding the dedicated public queue: they
  // claim the hosted identity directly instead of falling back to the local
  // claim path, and the queue keeps them off the main worker pool so a bulk
  // public selection cannot starve local+remote interpretation.
  private async deliver(
    { id: assetId, runKey: requestedRunKey, source, origin }: IAssetInterpretationJob,
    forcePublic: boolean,
  ): Promise<JobStatus> {
    const config = this.configRepository.getEnv().aiImageInterpretation;
    // Backlog-sweep compute saver: a delivery for an asset that already
    // carries any completed run (older prompt version, another model, a
    // public-spark run) is skipped instead of re-interpreted — public
    // deliveries included, since multi-select "Interpret image (public)"
    // cannot assume the user knows which assets are already interpreted.
    // Checked before claiming so a skipped delivery leaves no run record.
    // To force a re-interpretation (either lane), turn the flag off.
    if (config.skipIfInterpreted && (await this.hasCompletedInterpretation(assetId))) {
      // Log level (not debug): during the backlog sweep this is the only
      // visible signal that compute is being saved — skipped deliveries
      // produce no run record, alert, or metric.
      this.logger.log(`Skipping AI interpretation for ${assetId}: asset already has a completed interpretation`);
      return JobStatus.Skipped;
    }
    let runKey = requestedRunKey;
    if (!runKey && forcePublic) {
      runKey = createAiInterpretationPublicRunKey(config.publicModel, config.promptVersion);
    }
    if (!runKey) {
      // Bulk-script deliveries (origin: 'script') must not masquerade as upload
      // claims — the trigger feeds run provenance and retry tiering.
      runKey = await this.claimMissingRun(assetId, origin === 'script' ? { trigger: 'script' } : undefined);
      if (!runKey) {
        this.logger.debug(`Skipping manual AI interpretation request for ${assetId}`);
        return JobStatus.Skipped;
      }
    } else if (forcePublic || runKey === createAiInterpretationPublicRunKey(config.publicModel, config.promptVersion)) {
      // Manual "Interpret image (public)" delivery: claim the hosted identity.
      // The runKey encodes model + prompt version, so a completed run means
      // this asset already carries a public interpretation of the same
      // identity — skip it instead of re-sending the image. Bumping the
      // public model or prompt version changes the runKey and re-runs.
      // Ineligible assets skip without creating a run (no retry loop).
      if (!(await this.isInterpretationEligible(assetId))) {
        this.logger.debug(`Skipping public AI interpretation request for ${assetId}: asset not eligible`);
        return JobStatus.Skipped;
      }

      const claim = await this.interpretationRepository.claim(assetId, this.publicIdentity(config), new Date(), {
        trigger: 'manual-public',
      });
      if (claim.alreadyExists && (claim.run.status === 'running' || claim.run.status === 'completed')) {
        this.logger.debug(
          `Skipping public AI interpretation delivery for ${assetId}: ${claim.run.status} run already exists`,
        );
        return JobStatus.Skipped;
      }
    }

    const startedAt = Date.now();
    const started = await this.interpretationRepository.transitionToRunning(assetId, runKey);
    if (!started) {
      this.logger.debug(`Skipping duplicate AI interpretation delivery for ${assetId}/${runKey}`);
      return JobStatus.Skipped;
    }

    let input: AiInterpretationInput | undefined;
    let completed = false;
    let copied = false;
    try {
      if (!config.enabled) {
        throw new AiImageInterpretationClientError('feature_disabled', 'AI interpretation is disabled');
      }

      const document = await this.interpretationRepository.get(assetId);
      const run = document?.runs[runKey];
      if (!run) {
        throw new AiImageInterpretationClientError('invalid_output', 'AI interpretation run was not found');
      }

      const asset = await this.assetJobRepository.getForGenerateThumbnailJob(assetId);
      if (!asset || asset.type !== AssetType.Image || asset.visibility === AssetVisibility.Hidden) {
        throw new AiImageInterpretationClientError('preview_missing', 'Generated image preview is unavailable');
      }

      // The manual public run must actually call the hosted model: copying a
      // duplicate sibling's result (most often a local one) would defeat the
      // explicit per-image opt-in this run represents.
      const isPublic = run.quant === AI_INTERPRETATION_HOSTED_QUANT && run.model === config.publicModel;

      // Upload-sourced deliveries come from the duplicate-detection completion
      // event, so their analysis is final by construction. Everything else
      // (manual actions, ops scripts, retry requeues) waits out the analysis
      // instead of interpreting against a still-changing duplicate group —
      // except public runs, which never copy and so gain nothing from waiting.
      if (!isPublic && source !== 'upload' && (await this.isDuplicateAnalysisPending(assetId))) {
        const failure = { code: 'duplicates_pending', message: 'Duplicate detection has not completed yet' } as const;
        await this.interpretationRepository.fail(assetId, runKey, failure, { durationMs: Date.now() - startedAt });
        this.logger.debug(`Deferring AI interpretation for ${assetId} until duplicate detection completes`);
        return JobStatus.Success;
      }

      const copySource = isPublic ? null : await this.interpretationRepository.findCopySource(assetId, runKey);
      if (copySource) {
        completed = await this.interpretationRepository.completeCopy(assetId, runKey, copySource, {
          durationMs: Date.now() - startedAt,
        });
        copied = completed;
        if (completed) {
          this.logger.log(
            `Copied AI interpretation for ${assetId} from duplicate asset ${copySource.assetId} (run ${copySource.runKey})`,
          );
        }
      } else {
        const prepared = await this.preparePreview(asset);
        input = prepared.input;
        const response = await this.client.interpret(prepared.buffer, {
          model: run.model,
          ...(isPublic && { url: config.publicUrl, backendLabel: 'public-spark' }),
        });

        const served = response.model === run.model ? undefined : { model: response.model, quant: 'hosted' as const };
        completed = await this.interpretationRepository.complete(
          assetId,
          runKey,
          input,
          response.result,
          {
            durationMs: Date.now() - startedAt,
            promptTokens: response.promptTokens,
            completionTokens: response.completionTokens,
          },
          served,
        );
      }
    } catch (error) {
      const failure = this.asFailure(error);
      const metrics: AiInterpretationMetrics = { durationMs: Date.now() - startedAt };
      // Every failure retries with exponentially increasing delays capped at
      // one day (dispatched by the reconcile pass), with no attempt limit.
      // feature_disabled retries too: a deployment window that starts with the
      // feature off must not permanently strand already-queued runs.
      const updated = await this.interpretationRepository.fail(assetId, runKey, failure, metrics, input, new Date());
      this.logger.warn(
        `AI interpretation failed for ${assetId}: ${failure.code}${
          updated?.nextAttemptAt ? ` (retry scheduled for ${updated.nextAttemptAt})` : ' (no retry scheduled)'
        }`,
      );
    }

    if (completed) {
      try {
        await this.jobRepository.recordAiInterpretationCompletion(assetId, runKey);
      } catch (error) {
        this.logger.warn(
          `Failed to record AI interpretation completion sample for ${assetId}/${runKey}: ${
            error instanceof Error ? error.message : error
          }`,
        );
      }

      // Copied runs add no information the source run's alert did not already
      // cover, and a backlog drain would otherwise emit a burst of empty ones.
      if (config.discord.webhookUrl && !copied) {
        try {
          await this.jobRepository.queue({
            name: JobName.SendAiInterpretationDiscordAlert,
            data: { assetId, runKey },
          });
        } catch {
          this.logger.error(`Failed to queue Discord alert for AI interpretation ${assetId}/${runKey}`);
        }
      }

      // Embedding failure never fails interpretation: the sync job retries via
      // BullMQ backoff and the reconcile sweep re-covers gaps (design D5).
      if (this.configRepository.getEnv().aiInterpretSearch.enabled) {
        try {
          await this.jobRepository.queue({ name: JobName.AiInterpretSearchSync, data: { id: assetId } });
        } catch {
          this.logger.error(`Failed to queue AI interpret search sync for ${assetId}/${runKey}`);
        }
      }
    }

    return JobStatus.Success;
  }

  // The hosted ("public") run identity: the same prompt as local runs, but the
  // hosted router model the user manually opts into per image. `hosted` quant
  // distinguishes it from locally quantized GGUF identities.
  private publicIdentity(config: { publicModel: string; promptVersion: string }): AiInterpretationIdentity {
    return { model: config.publicModel, quant: AI_INTERPRETATION_HOSTED_QUANT, promptVersion: config.promptVersion };
  }

  // Any completed run in the asset's own document counts — copied runs and
  // public-spark runs included; failed or in-flight runs of other identities
  // never block.
  private async hasCompletedInterpretation(assetId: string): Promise<boolean> {
    const document = await this.interpretationRepository.get(assetId);
    if (!document) {
      return false;
    }

    return Object.values(document.runs).some((run) => run.status === 'completed');
  }

  private async isInterpretationEligible(assetId: string): Promise<boolean> {
    const config = this.configRepository.getEnv().aiImageInterpretation;
    if (!config.enabled) {
      return false;
    }

    const asset = await this.assetJobRepository.getForGenerateThumbnailJob(assetId);
    if (!asset || asset.type !== AssetType.Image || asset.visibility === AssetVisibility.Hidden) {
      return false;
    }

    return !!getAssetFile(asset.files, AssetFileType.Preview, { isEdited: false });
  }

  private async claimMissingRun(assetId: string, options?: AiInterpretationClaimOptions): Promise<string | undefined> {
    const config = this.configRepository.getEnv().aiImageInterpretation;
    if (!(await this.isInterpretationEligible(assetId))) {
      return;
    }

    const claim = await this.interpretationRepository.claim(
      assetId,
      {
        model: config.model,
        quant: config.quant,
        promptVersion: config.promptVersion,
      },
      new Date(),
      options,
    );
    return claim.alreadyExists ? undefined : claim.runKey;
  }

  // Whether duplicate-detection analysis can still change this asset's duplicate
  // group. Assets duplicate detection will never process (no job-status row —
  // the non-force scan inner-joins asset_job_status — stacked, hidden, locked)
  // are treated as concluded so they cannot be stranded here.
  private async isDuplicateAnalysisPending(assetId: string): Promise<boolean> {
    const { machineLearning } = await getConfig(
      {
        configRepo: this.configRepository,
        metadataRepo: this.systemMetadataRepository,
        logger: this.logger,
      },
      { withCache: true },
    );
    if (!isDuplicateDetectionEnabled(machineLearning)) {
      return false;
    }

    const state = await this.assetRepository.getDuplicateAnalysisState(assetId);
    if (
      !state ||
      state.stackId ||
      state.visibility === AssetVisibility.Hidden ||
      state.visibility === AssetVisibility.Locked
    ) {
      return false;
    }

    return !state.duplicatesDetectedAt;
  }

  @OnJob({ name: JobName.AssetInterpretationReconcile, queue: QueueName.ImageInterpretation })
  async handleReconcile(): Promise<JobStatus> {
    await this.reconcile();
    return JobStatus.Success;
  }

  private async reconcile() {
    const config = this.configRepository.getEnv().aiImageInterpretation;
    const timeoutMs = config.timeoutMs;
    const now = Date.now();
    // A queued run is only declared lost when its BullMQ job no longer exists
    // (e.g. queue state wiped); waiting behind a long backlog is not loss.
    const publicRunKey = createAiInterpretationPublicRunKey(config.publicModel, config.promptVersion);
    const failed = await this.interpretationRepository.failStale(new Date(now - timeoutMs), (assetId, runKey) =>
      // Public runs live in their own queue (and legacy pre-split public jobs
      // in the old one are deliberately NOT seen here): checking only the
      // run's own queue marks them orphaned so the reconcile re-dispatches
      // them through the public queue.
      this.jobRepository.jobExists(
        runKey === publicRunKey ? QueueName.ImageInterpretationPublic : QueueName.ImageInterpretation,
        createAiInterpretationJobId(assetId, runKey),
      ),
    );
    if (failed > 0) {
      this.logger.log(`Marked ${failed} stale AI interpretation run(s) as failed`);
    }

    const due = await this.interpretationRepository.findDueRetries(new Date());
    let dispatched = 0;
    for (const { assetId, runKey, assetCreatedAt } of due) {
      // Without this guard a failed run for an already-interpreted asset would
      // churn forever: requeue → delivery skipped → orphaned queued run →
      // failStale marks it failed → due again. Leaving it failed (retry stays
      // past-due) is stable, and reprocessing unblocks as soon as the flag is
      // turned off.
      if (config.skipIfInterpreted && (await this.hasCompletedInterpretation(assetId))) {
        continue;
      }
      const requeued = await this.interpretationRepository.requeue(assetId, runKey);
      if (!requeued) {
        continue;
      }

      // Tier 1 stays reserved for explicit "interpret now" actions, and public
      // runs return to their dedicated queue so retries cannot occupy the main
      // pool. Main-queue retries only re-enter the upload band (2) while their
      // asset is young enough to be a fresh upload's failing delivery (tier 2
      // is FIFO: an old-library run re-added there sits behind every newer
      // upload — at backlog scale it re-flooded tier 2 wholesale and new
      // uploads stopped being prompt). Older assets drop to the bulk band (3).
      const isPublic = runKey === publicRunKey;
      const isFreshUpload = Date.now() - assetCreatedAt.getTime() < UPLOAD_RETRY_MAX_ASSET_AGE_MS;
      await this.jobRepository.queue({
        name: isPublic ? JobName.AssetInterpretImagePublic : JobName.AssetInterpretImage,
        data: { id: assetId, runKey, priority: isPublic ? 1 : isFreshUpload ? 2 : 3 },
      });
      dispatched++;
    }

    if (dispatched > 0) {
      this.logger.log(`Requeued ${dispatched} due AI interpretation retry run(s)`);
    }
  }

  private async preparePreview(
    asset: Awaited<ReturnType<AssetJobRepository['getForGenerateThumbnailJob']>>,
  ): Promise<PreparedPreview> {
    const config = this.configRepository.getEnv().aiImageInterpretation;
    const preview = asset && getAssetFile(asset.files, AssetFileType.Preview, { isEdited: false });
    if (!asset || !preview) {
      throw new AiImageInterpretationClientError('preview_missing', 'Generated image preview is unavailable');
    }

    try {
      const metadata = await sharp(preview.path, { limitInputPixels: MAX_DECODE_PIXELS }).metadata();
      if (!metadata.width || !metadata.height) {
        throw new AiImageInterpretationClientError('preview_invalid', 'Generated image preview could not be decoded');
      }

      if (metadata.width * metadata.height > config.maxPixels) {
        this.logger.log(
          `Clamping oversized AI interpretation preview (${metadata.width}x${metadata.height}) to a ${config.maxEdge}px edge`,
        );
      }

      const output = await sharp(preview.path, { limitInputPixels: MAX_DECODE_PIXELS })
        .rotate()
        .resize(config.maxEdge, config.maxEdge, { fit: 'inside', withoutEnlargement: true })
        .jpeg({ quality: 85 })
        .toBuffer({ resolveWithObject: true });

      const { width, height } = output.info;
      if (!width || !height || width > config.maxEdge || height > config.maxEdge || width * height > config.maxPixels) {
        throw new AiImageInterpretationClientError(
          'preview_too_large',
          'Prepared preview exceeds the configured bound',
        );
      }

      return {
        buffer: output.data,
        input: { source: 'preview', width, height, mimeType: 'image/jpeg' },
      };
    } catch (error) {
      if (error instanceof AiImageInterpretationClientError) {
        throw error;
      }
      if (error instanceof Error && /pixel|limitInputPixels/i.test(error.message)) {
        throw new AiImageInterpretationClientError(
          'preview_too_large',
          'Generated image preview exceeds the pixel limit',
        );
      }
      throw new AiImageInterpretationClientError('preview_invalid', 'Generated image preview could not be decoded');
    }
  }

  private asFailure(error: unknown) {
    if (error instanceof AiImageInterpretationClientError) {
      return { code: error.code, message: error.message.slice(0, 200) };
    }

    return { code: 'internal_error', message: 'AI interpretation failed before completion' };
  }
}
